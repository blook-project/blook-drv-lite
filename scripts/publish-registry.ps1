# Produces (or publishes) the blook-xmake-repo manifest for this release.
#
#   ./scripts/publish-registry.ps1 -DryRun -OutDir artifacts
#   ./scripts/publish-registry.ps1            # clones blook-xmake-repo and pushes
#
# The real run uses `gh repo clone`, copies the package definition into
# packages/<letter>/blook-drv-lite/ and commits on main. No token is embedded:
# `gh auth` must already be logged in (local run) or REPO_TOKEN configured.
[CmdletBinding()]
param(
    [switch]$DryRun,
    [string]$OutDir = "artifacts",
    [string]$RepoRoot = (Split-Path -Parent $PSScriptRoot)
)
$ErrorActionPreference = "Stop"
$Version = (Get-Content (Join-Path $RepoRoot "version.txt") -Raw).Trim()
$Out = if ([IO.Path]::IsPathRooted($OutDir)) { $OutDir } else { Join-Path $RepoRoot $OutDir }

$manifest = @"
-- blook-drv-lite $Version package definition (generated by
-- scripts/publish-registry.ps1; do not edit in the registry).
package("blook-drv-lite")
    set_homepage("https://github.com/blook-project/blook-drv-lite")
    set_description("Lite manual-map kernel driver + user-mode SDK (memory r/w, DSE, ObReference bypass, InfinityHook)")
    set_license("MIT")
    set_urls("https://github.com/blook-project/blook-drv-lite/releases/download/v$Version/blook-drv-lite-$Version.zip")
    -- add_versions("$Version", "<sha256>")  # filled by package.ps1 output
    on_install("windows|x64", function (package)
        os.cp("include", package:installdir())
        os.cp("lib/drvlite.lib", package:installdir("lib"))
        os.cp("xmake-package/xmake.lua", package:installdir())
    end)
"@

New-Item -ItemType Directory -Force $Out | Out-Null
$manifestPath = Join-Path $Out "blook-drv-lite-package.lua"
Set-Content -Path $manifestPath -Value $manifest -Encoding utf8
Write-Host "registry manifest: $manifestPath"

$shaFile = Get-ChildItem $Out -Filter "blook-drv-lite-$Version.zip.sha256" -ErrorAction SilentlyContinue
if ($shaFile) {
    $sha = (Get-Content $shaFile.FullName -Raw).Split(" ")[0]
    (Get-Content $manifestPath -Raw).Replace("<sha256>", $sha) |
        Set-Content $manifestPath -Encoding utf8
    Write-Host "sha256 embedded: $sha"
}

if ($DryRun) {
    Write-Host "dry run: registry repo not modified"
    return
}

$temp = Join-Path ([IO.Path]::GetTempPath()) ("blook-xmake-repo-" + [guid]::NewGuid())
try {
    gh repo clone blook-project/blook-xmake-repo $temp -- --depth 1
    $packageDir = Join-Path $temp "packages\b\blook-drv-lite"
    New-Item -ItemType Directory -Force $packageDir | Out-Null
    Copy-Item $manifestPath (Join-Path $packageDir "xmake.lua") -Force
    Push-Location $temp
    git add -A
    git -c user.name="MicroBlock" `
        -c user.email="66859419+std-microblock@users.noreply.github.com" `
        commit -m "registry: blook-drv-lite $Version"
    git push
    Pop-Location
    Write-Host "registry updated for $Version"
} finally {
    if (Test-Path $temp) { Remove-Item -Recurse -Force $temp }
}
